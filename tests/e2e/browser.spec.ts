test('关闭滚动时新字幕不抢占回看位置', async ({ page }) => {
  await page.getByRole('button', { name: '开始翻译', exact: true }).click()
  await page.clock.runFor(30000)
  await page.getByRole('button', { name: '字幕设置' }).click()
  await page.getByLabel('自动滚动').uncheck()
  await page.getByRole('button', { name: '关闭设置' }).click()
  await page.locator('.feed').evaluate((el) => {
    el.scrollTop = 0
  })
  await page.clock.runFor(6000)
  expect(await page.locator('.feed').evaluate((el) => el.scrollTop)).toBe(0)
  await page.screenshot({ path: 'work/screenshots/listening.png' })
})

test('默认自动滚动持续跟随最新字幕，设置重载后仍生效', async ({ page }) => {
  await page.getByRole('button', { name: '开始翻译', exact: true }).click()
  await page.clock.runFor(31000)
  await expect(page.locator('.caption').last()).toBeInViewport()
  await page.getByRole('button', { name: '字幕设置' }).click()
  await page.getByLabel('保留技术术语').uncheck()
  await page.getByRole('button', { name: '关闭设置' }).click()
  await page.getByRole('button', { name: '仅中文', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('button', { name: '开始翻译', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '字幕设置' }).click()
  await expect(page.getByLabel('保留技术术语')).not.toBeChecked()
  await page.getByRole('button', { name: '关闭设置' }).click()
  await page.getByRole('button', { name: '开始翻译', exact: true }).click()
  await page.clock.runFor(10000)
  await expect(page.locator('.english')).toHaveCount(0)
  await expect(page.locator('.chinese').nth(1)).toContainText('检索增强生成')
})

test('窄窗口初始页的开始按钮与说明不挤入工具栏', async ({ page }) => {
  await page.setViewportSize({ width: 600, height: 760 })
  const bounds = await page.locator('.welcome').boundingBox()
  const illustration = await page.locator('.orbit-ring.two').boundingBox()
  const last = await page.locator('.feature-strip').boundingBox()
  expect(illustration!.y).toBeGreaterThanOrEqual(bounds!.y)
  if (last) expect(last.y + last.height).toBeLessThanOrEqual(bounds!.y + bounds!.height)
})

test('浏览器结束后提供真实 Markdown 下载，不显示桌面保存成功', async ({ page }) => {
  await page.getByRole('button', { name: '开始翻译', exact: true }).click()
  await page.clock.runFor(1200)
  await page.getByRole('button', { name: '结束', exact: true }).click()
  await expect(page.getByText('浏览器预览：记录尚未保存，请下载')).toBeVisible()
  const result = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载记录' }).click()
  const download = await result
  expect(download.suggestedFilename()).toMatch(/\.md$/)
  const stream = await download.createReadStream()
  let text = ''
  for await (const chunk of stream!) text += chunk.toString()
  expect(text).toContain('模拟数据')
  expect(text).toContain('未确认')
  expect(text).toContain('Today')
  await expect(page.getByText('已保存到桌面「实译历史记录」', { exact: true })).toHaveCount(0)
})
