import { test, expect } from '@playwright/test'
test.beforeEach(async ({ page }) => {
  await page.clock.install()
  await page.goto('/')
})
test('完整操作链路、复制与重新开始确认', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await expect(page.getByRole('heading', { name: '让理解，跟上每一句。' })).toBeVisible()
  await page.getByRole('button', { name: '开始翻译', exact: true }).click()
  await page.clock.runFor(1200)
  await expect(page.locator('.caption')).toHaveCount(1)
  await page.getByRole('button', { name: '暂停', exact: true }).click()
  const frozen = await page.locator('.feed').innerText()
  await page.clock.runFor(8000)
  expect(await page.locator('.feed').innerText()).toBe(frozen)
  await page.getByRole('button', { name: '继续翻译', exact: true }).click()
  await page.clock.runFor(5000)
  await expect(page.locator('.caption.final')).toHaveCount(1)
  await page.getByRole('button', { name: '结束', exact: true }).click()
  await expect(page.getByText('翻译已结束')).toBeVisible()
  await page.getByRole('button', { name: '复制全部', exact: true }).click()
  expect(await page.evaluate(() => navigator.clipboard.readText())).toContain('RAG')
  await page.getByRole('button', { name: '重新开始', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.locator('.caption')).toHaveCount(2)
  await page.getByRole('button', { name: '重新开始', exact: true }).click()
  await page.getByRole('button', { name: '确认重新开始' }).click()
  await expect(page.locator('.caption')).toHaveCount(0)
})
